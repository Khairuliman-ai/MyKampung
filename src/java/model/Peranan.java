package model;

public class Peranan {
    private int id_peranan;
    private String nama_peranan;

    // Getters and Setters
    public int getId_peranan() { return id_peranan; }
    public void setId_peranan(int id_peranan) { this.id_peranan = id_peranan; }

    public String getNama_peranan() { return nama_peranan; }
    public void setNama_peranan(String nama_peranan) { this.nama_peranan = nama_peranan; }
}